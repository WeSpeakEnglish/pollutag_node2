/**
  ******************************************************************************
  * @file    lorawan_credentials_template.h
  * @brief   LoRaWAN OTAA credentials of a device (TEMPLATE)
  ******************************************************************************
  * Copy this file to lorawan_credentials.h (same folder) and fill in the
  * values of your device. lorawan_credentials.h is device specific and secret.
  *
  * Values: comma separated hex bytes, big endian (MSB first), exactly as shown
  * in the network console (TTN, Helium, ChirpStack, ...).
  *
  *   DEVICE_EUI  8 bytes  all 00 = use the MCU unique ID (printed at boot as
  *                        "DevEUI: ..." on the debug UART, 115200 baud)
  *   JOIN_EUI    8 bytes  (AppEUI in LoRaWAN 1.0.x), may be all 00
  *   APP_KEY    16 bytes  root key used for the OTAA join
  *
  * This file is included by se-identity.h (USER CODE section) and overrides the
  * values generated by CubeMX, so the .ioc never has to contain real keys.
  ******************************************************************************
  */
#ifndef LORAWAN_CREDENTIALS_H
#define LORAWAN_CREDENTIALS_H

#define LORAWAN_DEVICE_EUI    00,00,00,00,00,00,00,00
#define LORAWAN_JOIN_EUI      00,00,00,00,00,00,00,00
#define LORAWAN_APP_KEY       00,00,00,00,00,00,00,00,00,00,00,00,00,00,00,00

/* LoRaWAN 1.0.x: the network root key is the same as the AppKey */
#define LORAWAN_NWK_KEY       LORAWAN_APP_KEY

#endif /* LORAWAN_CREDENTIALS_H */
